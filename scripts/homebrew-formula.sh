#!/usr/bin/env bash
# Print the Homebrew formula for a release.
# Usage: scripts/homebrew-formula.sh <tag> <SHA256SUMS.txt>
set -euo pipefail

tag="${1:?usage: homebrew-formula.sh <tag> <SHA256SUMS.txt>}"
sums="${2:?usage: homebrew-formula.sh <tag> <SHA256SUMS.txt>}"
version="${tag#v}"

sha() {
  local name="sarah-${tag}-$1.tar.gz" hash
  hash="$(awk -v n="$name" '$2 == n { print $1 }' "$sums")"
  if [[ ! "$hash" =~ ^[0-9a-f]{64}$ ]]; then
    echo "missing checksum for $name in $sums" >&2
    exit 1
  fi
  echo "$hash"
}

mac_arm="$(sha aarch64-apple-darwin)"
mac_intel="$(sha x86_64-apple-darwin)"
linux_arm="$(sha aarch64-unknown-linux-musl)"
linux_intel="$(sha x86_64-unknown-linux-musl)"

cat <<EOF
# Generated by scripts/homebrew-formula.sh in aiman2039/sarah. Do not edit.
class Sarah < Formula
  desc "Count tokens, lines and function sizes per file to guide refactoring"
  homepage "https://github.com/aiman2039/sarah"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "https://github.com/aiman2039/sarah/releases/download/${tag}/sarah-${tag}-aarch64-apple-darwin.tar.gz"
      sha256 "${mac_arm}"
    end
    on_intel do
      url "https://github.com/aiman2039/sarah/releases/download/${tag}/sarah-${tag}-x86_64-apple-darwin.tar.gz"
      sha256 "${mac_intel}"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/aiman2039/sarah/releases/download/${tag}/sarah-${tag}-aarch64-unknown-linux-musl.tar.gz"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "https://github.com/aiman2039/sarah/releases/download/${tag}/sarah-${tag}-x86_64-unknown-linux-musl.tar.gz"
      sha256 "${linux_intel}"
    end
  end

  def install
    bin.install "sarah"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/sarah --version")
  end
end
EOF
